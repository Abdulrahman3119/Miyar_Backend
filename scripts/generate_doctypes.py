def _simple(name, autoname="field:code", extras=None, title="التسمية"):
	fields = []
	if autoname.startswith("field:"):
		fn = autoname.split(":", 1)[1]
		if fn == "code":
			fields.append(f("code", "Data", "الرمز", reqd=1, unique=1, in_list=1, in_std=1))
			fields.append(f("label_ar", "Data", title, reqd=1, in_list=1))
		elif fn == "label_ar":
			fields.append(f("label_ar", "Data", title, reqd=1, unique=1, in_list=1))
			fields.append(f("code", "Data", "الرمز", in_std=1))
		else:
			fields.append(f(fn, "Data", title, reqd=1, unique=1, in_list=1))
			fields.append(f("label_ar", "Data", "التسمية", reqd=1, in_list=1))
	fields.append(f("is_active", "Check", "فعّال", default="1", in_list=1))
	fields.append(f("sort_order", "Int", "الترتيب"))
	if extras:
		fields.extend(extras)
	tf = "label_ar" if any(x["fieldname"] == "label_ar" for x in fields) else None
	return dt(
		name,
		fields,
		autoname=autoname,
		title_field=tf,
		search_fields="code,label_ar",
		permissions=master_perms(),
		quick_entry=1,
		track_changes=1,
	)


