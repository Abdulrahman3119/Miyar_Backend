def all_doctypes():
	return children() + masters() + settings_and_party() + catalog_and_commercial() + operations() + rest()


def main():
	docs = all_doctypes()
	names = [d["name"] for d in docs]
	dupes = {n for n in names if names.count(n) > 1}
	if dupes:
		raise SystemExit(f"Duplicate DocTypes: {dupes}")
	for doc in docs:
		write_doctype(APP_ROOT, doc)
	print(f"Wrote {len(docs)} DocTypes ({sum(1 for d in docs if d.get('istable'))} child tables).")


if __name__ == "__main__":
	main()
